/**
 * Style Dictionary formats shared by GDL and every brand built on it.
 *
 * GDL builds its own dist/ with these, and brand repos (VCP, CAF, …) import
 * them instead of keeping their own copy:
 *
 *   import StyleDictionary from 'style-dictionary';
 *   import { registerGdlFormats, gdlPlatforms, gdlIncludes } from '@vdm-design-team/gdl/build';
 *
 *   registerGdlFormats(StyleDictionary);
 *   export default {
 *     include: gdlIncludes(),            // GDL core + type ramp (lower priority)
 *     source: ['tokens/**\/*.json'],      // the brand's own tokens win on collisions
 *     platforms: gdlPlatforms(),
 *   };
 *
 * Tailwind v4 mapping — every token path lands in a Tailwind namespace so it
 * becomes a utility class:
 *
 *   color.<family>.<step>             --color-*        bg-slate-100, text-blue-500
 *   surface|text|stroke|action|accent|neutral.*
 *                                     --color-*        bg-surface-canvas, text-text-primary
 *   radius.*                          --radius-*       rounded-8, rounded-full
 *   shadow.elevation.*                --shadow-*       shadow-elevation-3
 *   font.family.*                     --font-*         font-sans, font-numeric
 *   font.weight.*                     --font-weight-*  font-semibold
 *   type.*                            --text-*         text-body-md-regular (size + line height + weight + tracking)
 *
 * space.* and stroke-width.* are not mapped: GDL's px spacing equals
 * Tailwind's numeric scale (4px = p-1), so components use the p-* and gap-* utilities; both
 * scales are still emitted as custom properties in tokens.css.
 *
 * Mode roots (`dark`, `desktop`) hold overrides of the same paths and are
 * emitted as separate CSS files scoped to a selector.
 */

export const MODES = [
  { root: 'dark', selector: '.dark', file: 'tokens.dark.css', note: 'Dark theme — apply .dark on <html> (or any ancestor).' },
  { root: 'desktop', selector: '[data-type-scale="desktop"]', file: 'typography.desktop.css', note: 'Desktop type sizes — opt in with data-type-scale="desktop". Not wired into the text-* ramp yet.' },
];
const MODE_ROOTS = MODES.map((m) => m.root);
const SEMANTIC_ROOTS = ['surface', 'text', 'stroke', 'action', 'accent', 'neutral'];

/** Tailwind theme variable name for a token path (without a mode root), or null if it has no Tailwind namespace. */
export const tailwindName = (path) => {
  const [root, ...rest] = path;
  if (root === 'color') return `color-${rest.join('-')}`;
  if (SEMANTIC_ROOTS.includes(root)) return `color-${path.join('-')}`;
  if (root === 'radius') return `radius-${rest.join('-')}`;
  if (root === 'shadow') return `shadow-${rest.join('-')}`;
  if (root === 'font' && rest[0] === 'family') return `font-${rest.slice(1).join('-')}`;
  if (root === 'font' && rest[0] === 'weight') return `font-weight-${rest.slice(1).join('-')}`;
  return null;
};

const valueOf = (t) => t.$value ?? t.value;
const isMode = (t) => MODE_ROOTS.includes(t.path[0]);

/** Registers the GDL formats on a Style Dictionary instance. Safe to call more than once. */
export function registerGdlFormats(StyleDictionary) {
  StyleDictionary.registerFormat({
    name: 'gdl/tailwind-theme',
    format: ({ dictionary, options }) => {
      const lines = [];
      for (const t of dictionary.allTokens) {
        if (isMode(t) || t.path[0] === 'type') continue;
        const name = tailwindName(t.path);
        if (name) lines.push(`  --${name}: ${valueOf(t)};${t.$description ? ` /* ${t.$description.replace(/\*\//g, '* /')} */` : ''}`);
      }
      /* Type ramp → text-* utilities with paired line height, weight and tracking. */
      const weightOf = (ref) => {
        const m = String(ref).match(/^\{(.+)\}$/);
        if (!m) return ref;
        const target = dictionary.allTokens.find((x) => x.path.join('.') === m[1]);
        return target ? valueOf(target) : ref;
      };
      for (const t of dictionary.allTokens.filter((x) => x.path[0] === 'type')) {
        const style = t.path.slice(1).join('-');
        const v = t.original.$value ?? t.original.value;
        if (!v || typeof v !== 'object') continue;
        lines.push(`  --text-${style}: ${v.fontSize};`);
        lines.push(`  --text-${style}--line-height: ${v.lineHeight};`);
        lines.push(`  --text-${style}--font-weight: ${weightOf(v.fontWeight)};`);
        if (v.letterSpacing) lines.push(`  --text-${style}--letter-spacing: ${v.letterSpacing};`);
      }
      const imports = (options?.modeFiles ?? MODES.map((m) => m.file)).map((f) => `@import "./${f}";`);
      return [
        '/* AUTOGENERATED by Style Dictionary (GDL formats) — do not edit. */',
        '@import "tailwindcss";',
        '',
        '@theme {',
        ...lines,
        '}',
        '',
        ...imports,
        '',
      ].join('\n');
    },
  });

  StyleDictionary.registerFormat({
    name: 'gdl/mode-overrides',
    format: ({ dictionary, options }) => {
      const { root, selector, note } = options;
      const lines = dictionary.allTokens
        .filter((t) => t.path[0] === root)
        .map((t) => {
          const path = t.path.slice(1);
          return `  --${tailwindName(path) ?? path.join('-')}: ${valueOf(t)};`;
        });
      return [`/* AUTOGENERATED — ${note ?? root} */`, `${selector} {`, ...lines, '}', ''].join('\n');
    },
  });

  StyleDictionary.registerFormat({
    name: 'gdl/ts-tokens',
    format: ({ dictionary }) => {
      const obj = {};
      for (const t of dictionary.allTokens) {
        let cur = obj;
        t.path.forEach((seg, i) => {
          if (i === t.path.length - 1) cur[seg] = valueOf(t);
          else cur = cur[seg] ??= {};
        });
      }
      return `// AUTOGENERATED by Style Dictionary (GDL formats) — do not edit.\nexport const tokens = ${JSON.stringify(obj, null, 2)} as const;\nexport type Tokens = typeof tokens;\n`;
    },
  });
}

/** The platforms block every GDL-based repo uses. */
export const gdlPlatforms = ({ buildPath = 'dist/' } = {}) => ({
  tailwind: {
    transformGroup: 'css',
    buildPath,
    files: [
      { destination: 'theme.css', format: 'gdl/tailwind-theme' },
      ...MODES.map((m) => ({ destination: m.file, format: 'gdl/mode-overrides', options: m })),
    ],
  },
  css: {
    transformGroup: 'css',
    buildPath,
    files: [{ destination: 'tokens.css', format: 'css/variables', filter: (t) => !isMode(t), options: { outputReferences: true } }],
  },
  ts: {
    transformGroup: 'js',
    buildPath,
    files: [{ destination: 'tokens.ts', format: 'gdl/ts-tokens' }],
  },
  json: {
    transformGroup: 'js',
    buildPath,
    files: [
      { destination: 'tokens.flat.json', format: 'json/flat' },
      { destination: 'tokens.json', format: 'json/nested' },
    ],
  },
});

/**
 * Token files a brand includes from GDL. Everything under tokens/ — core
 * scales, modes and the type ramp — but never the reference theme, which is
 * GDL's own placeholder semantics.
 */
export const gdlIncludes = (pkgDir = 'node_modules/@vdm-design-team/gdl') => [`${pkgDir}/tokens/**/*.json`];
